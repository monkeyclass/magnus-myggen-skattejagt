#!/usr/bin/env python3
"""Generates the native setup of the game's objects (scripts/setup.cpp)
from a recording of the original setup code (FUN_0043f760), made with the
engine's "record_setup=<file>" option.

The original setup functions (each class's slots 3 and 4) are straight-line
constructor calls, so the recording of the engine calls they make is the
setup: objects, their variables, their children and the children's
settings, in the original order.

usage: gensetup.py setup.rec > setup.cpp
"""
import re
import sys

# EngineFunc ids of machine.cpp
OBJ_CTOR, ADD_CHILD, CHILD_CURSOR = 0, 4, 10
NEW_BITMAP, NEW_ANIM, NEW_HOTSPOT, NEW_SOUND, NEW_TEXTRES, NEW_TEXT, NEW_VIDEO = 11, 12, 13, 14, 15, 16, 17
REGISTER = 19
ADD_INT, ADD_STRING, ADD_RANDOM, ADD_CYCLER, ADD_SHUFFLE, ADD_MAP = 33, 34, 35, 36, 37, 38
IGNORED = {5, 6, 18, 20, 21, 22, 23}  # lookups and allocations

